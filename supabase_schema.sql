-- STORAGE — verification bucket
-- =============================================================================
insert into storage.buckets (id, name, public)
values ('verification', 'verification', true)
on conflict (id) do nothing;

-- Allow authenticated users to upload to verification bucket
create policy "verification_insert_own" on storage.objects
  for insert
  with check (
    bucket_id = 'verification'
    and auth.role() = 'authenticated'
  );

-- Allow public read of verification files
create policy "verification_select_public" on storage.objects
  for select
  using (bucket_id = 'verification');

-- =============================================================================
-- RPC — admin operations (bypass RLS via security definer)
-- =============================================================================
create or replace function public.admin_update_user_status(p_uid text, p_status text)
returns void
security definer
set search_path = public
language plpgsql as $$
begin
  update public.users set driver_status = p_status where uid = p_uid;
end;
$$;

-- =============================================================================
-- TRIGGERS — auto-update updated_at
-- =============================================================================
create or replace function public.set_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

do $$
begin
  if not exists (select 1 from pg_trigger where tgname = 'set_users_updated_at') then
    create trigger set_users_updated_at before update on public.users
      for each row execute function public.set_updated_at();
  end if;
  if not exists (select 1 from pg_trigger where tgname = 'set_orders_updated_at') then
    create trigger set_orders_updated_at before update on public.orders
      for each row execute function public.set_updated_at();
  end if;
end;
$$;

