-- 1. Users
-- =============================================================================
create table if not exists public.users (
  id            bigint generated by default as identity primary key,
  uid           text unique not null,
  username      text not null default '',
  name          text not null default '',
  email         text not null default '',
  role          text not null default 'client',
  image_url     text not null default '',
  rating        numeric(3,2) default 5.0,
  vehicle_type  text default '',
  vehicle_plate text default '',
  vehicle_capacity text default '',
  trips_count   int default 0,
  years_active  int default 1,
  about         text default '',
  reviews       jsonb default '[]'::jsonb,
  is_verified   boolean default false,
  verification_status text default 'unsubmitted',
  driver_status text default '',
  is_available  boolean default true,
  current_lat   numeric(10,7) default 30.0444,
  current_long  numeric(10,7) default 31.2357,
  national_id   text default '',
  license_number text default '',
  id_front_image  text default '',
  id_back_image   text default '',
  license_image   text default '',
  vehicle_image   text default '',
  created_at    timestamptz default now(),
  updated_at    timestamptz default now(),
  fcm_token     text default '',
  profile_image text default '',
  phone         text default '',
  address       text default '',
  is_deleted    boolean default false,
  deleted_at    timestamptz,
  notification_settings jsonb default '{}'::jsonb,
  reward_points int default 0
);

comment on table public.users is 'User profiles — clients, drivers, admins';

-- Indexes
create index if not exists idx_users_uid on public.users (uid);
create index if not exists idx_users_role on public.users (role);
create index if not exists idx_users_driver_status on public.users (driver_status);
create index if not exists idx_users_verification_status on public.users (verification_status);

-- 2. Orders (Shipments)
-- =============================================================================
